"""The candidate expected-return sources, the prior-evidence map, and a declared ranking.

`NON_DECISION_BEARING_EXPLORATORY_ONLY` · `RESEARCH_SCRATCH_NON_AUTHORITATIVE`.

Every candidate names the prior evidence it overlaps, classified exactly as that
evidence stands in the ledger (`scripts/research/round_a/ledger.py`), the
decision-grade inventory (`artifacts/research/feasibility/inventory.json`) or a
merged phase record. A candidate that only renames a closed family is kept in the
catalogue and marked excluded, so the exclusion itself is visible.

The ranking is a judgement with declared weights, not a measurement. Scores are
set from mechanism, prior evidence, data access and the capacity arithmetic in
`capacity.py` — never from a backtest, because none was run.
"""

