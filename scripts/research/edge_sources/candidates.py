def ranking() -> list[dict[str, object]]:
    rows = [
        {"cid": c.cid, "score": score(c), "eligibility": c.eligibility, "name": c.name}
        for c in CANDIDATES
    ]
    eligible = sorted(
        (r for r in rows if r["eligibility"] == ACTIVE), key=lambda r: (-int(r["score"]), r["cid"])
    )
    others = sorted(
        (r for r in rows if r["eligibility"] != ACTIVE), key=lambda r: (-int(r["score"]), r["cid"])
    )
    for rank, row in enumerate(eligible, start=1):
        row["rank"] = rank
    for row in others:
        row["rank"] = None
    return eligible + others


def distinct_directions() -> list[str]:
    """Candidates that are neither a rename of a closed family nor an increment of another."""
    return [c.cid for c in CANDIDATES if c.eligibility != EXCLUDED and not c.increment_of]


